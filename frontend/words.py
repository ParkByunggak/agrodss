def plain(text: str) -> str:
    """시스템이 만든 문장을 사람 말로. **농가가 쓴 글에는 쓰지 않는다.**"""
    out = _ID_TAG.sub("", text or "")
    out = _STAGE_NO.sub(r"\1단계", out)
    for a, b in SWAPS:
        out = out.replace(a, b)
    return out
