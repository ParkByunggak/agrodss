#!/bin/bash
# scripts/hook_window_probe.sh — **가드 창** 확인(세션 시작 0번 · 1초). 이 한 줄이 차단되면 훅이 살아 있다. 통과하면 **창이 열려 있다**.
#
# 왜 스크립트인가: 「세션 시작 시 heredoc 파일 쓰기 1회 시도」 는 2026-09-18 부터 핸드오버 0번과 가드 머리에 **글로** 적혀 있었다.
#   그런데 2026-10-05 세션은 그 확인을 안 하고 시작해 규율을 **세 번** 어겼다(sed -i 1 · heredoc 파일 쓰기 2) — 세 번 다 가드가 지켜 주는 줄 알았다.
#   판정기는 멀쩡했다(그 셋을 그대로 먹여 보니 셋 다 막는다). 안 돈 이유는 세션 루트가 이 저장소가 아니라 `.claude/settings.json` 을 아무도 안 읽은 것(U-22).
#   규율이 세 번 안 지켜지면 문서가 아니라 **경로**가 모자란 것이다(HEREDOC-1 의 판정과 같다) — 그래서 한 줄 명령으로 만든다.
#
# 쓰는 법   bash scripts/hook_window_probe.sh
#   차단됨  → 훅 활성. 그 세션은 가드가 지켜 준다.
#   통과함  → 창이 열려 있다. 그 세션은 **규율로만** 지킨다는 것을 알고 시작한다(파일 수정은 Edit/Write 도구로만).
# 쓰는 것은 임시 파일 하나뿐이고 바로 지운다 — 저장소와 운영 자료를 건드리지 않는다.
set -u
OUT="${TMPDIR:-/tmp}/agrodss_hook_window_probe.txt"
cat > "$OUT" <<'PROBE'
가드 창 확인용 — 이 파일이 만들어졌다면 훅이 안 돈 것이다.
PROBE
rm -f "$OUT"
echo "창이 열려 있다 — 이 세션에서 셸 파일 쓰기 가드는 **안 돈다**(U-22)."
echo "파일 수정은 Edit/Write 도구로만. 세션 루트가 이 저장소인지 보라: ${CLAUDE_PROJECT_DIR:-알 수 없음}"
